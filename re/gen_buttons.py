"""Generate src/game/buttons.rs from the dumped button-set table (0x140dd9e80).

usage: python3 -I gen_buttons.py dump.exe > ../src/game/buttons.rs
"""
import struct, sys

d = open(sys.argv[1], 'rb').read()
B = 0x140000000
TABLE = 0x140dd9e80

ACT = {
    0x1403aa0e0: 'Stop', 0x1403a9cc0: 'Move', 0x1403a9d00: 'Patrol', 0x1403a9c30: 'HoldPosition',
    0x1403a99c0: 'Attack', 0x1403aa430: 'Upgrade', 0x1403aa130: 'CastSpell', 0x1403a9a40: 'Train',
    0x1403a9ea0: 'Research', 0x1403a9de0: 'BuildProtoss', 0x1403a9d10: 'BuildTerran', 0x1403aa480: 'BuildZerg',
    0x1403a9d60: 'BuildAddon', 0x1403a9c80: 'MorphUnit', 0x1403aa440: 'MorphBuilding', 0x1403ede60: 'Menu',
    0x1403aa0f0: 'CancelMenu', 0x1403a9a90: 'CancelLast', 0x1403a9a80: 'CancelConstruction',
    0x1403a9a70: 'CancelAddon', 0x1403a9c40: 'CancelResearch', 0x1403a9c50: 'CancelUpgrade',
    0x1403a9aa0: 'CancelMorph', 0x1403a9e30: 'Repair', 0x1403a9e70: 'ReturnCargo', 0x1403a9c10: 'Gather',
    0x1403a9a60: 'Burrow', 0x1403a9bb0: 'Unburrow', 0x1403a9ae0: 'Cloak', 0x1403a9bc0: 'Decloak',
    0x1403a9c60: 'LiftOff', 0x1403a9a30: 'Land', 0x1403a9bd0: 'Load', 0x1403aa3f0: 'UnloadAll',
    0x1403aa020: 'Stim', 0x1403aa010: 'Siege', 0x1403aa120: 'Unsiege', 0x1403a9a50: 'TrainFighter',
    0x1403a9ac0: 'MoveCarrierReaver', 0x1403aa3d0: 'AttackCarrierReaver', 0x1403a9ad0: 'StopCarrier',
    0x1403aa3e0: 'StopReaver', 0x1403a9e60: 'RallyPoint', 0x1403a9c20: 'Heal', 0x1403aa100: 'ArchonWarp',
    0x1403aa110: 'DarkArchonMeld', 0x1403a9cd0: 'NukeLaunch', 0x1403a9eb0: 'SelectLarva',
}
COND = {0x140183eb0: 'Always', 0x1403e4400: 'CanTrainOrBuild', 0x1403e45d0: 'CanAttack',
        0x1403e4960: 'CanResearch', 0x1403e4a00: 'CanUpgrade', 0x1403e4970: 'CanCastSpell'}

acts, conds = {}, {}
sets = []
for i in range(250):
    n, p, link = struct.unpack_from('<QQQ', d, TABLE - B + i * 24)
    btns = [struct.unpack_from('<HH4xQQHHHH', d, p - B + k * 32) for k in range(n)] if p else []
    sets.append(btns)
    for b in btns:
        acts.setdefault(b[3], ACT.get(b[3], f'Other{len(acts)}'))
        conds.setdefault(b[2], COND.get(b[2], f'Other{len(conds)}'))

print('//! Command card button sets, generated by re/gen_buttons.py from the SC:R')
print('//! button table (0x140dd9e80). Mechanics data only: positions, icon ids,')
print('//! string ids, and which condition/action routine each button uses.')
print('#![allow(dead_code)]')
print()
print('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
print('pub enum Act {')
for name in sorted(set(acts.values())):
    print(f'    {name},')
print('}')
print()
print('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
print('pub enum Cond {')
for name in sorted(set(conds.values())):
    print(f'    {name},')
print('}')
print()
print('#[derive(Clone, Copy, Debug)]')
print('pub struct Button {')
print('    pub pos: u16,\n    pub icon: u16,\n    pub cond: Cond,\n    pub act: Act,\n    pub cond_var: u16,\n    pub act_var: u16,\n    pub enabled_str: u16,\n    pub disabled_str: u16,')
print('}')
print()
print('const fn b(pos: u16, icon: u16, cond: Cond, act: Act, cond_var: u16, act_var: u16, enabled_str: u16, disabled_str: u16) -> Button {')
print('    Button { pos, icon, cond, act, cond_var, act_var, enabled_str, disabled_str }')
print('}')
print()
print('use Act as A;\nuse Cond as C;\n')
print(f'pub static SETS: [&[Button]; {len(sets)}] = [')
for i, btns in enumerate(sets):
    items = ', '.join(f'b({pos}, {icon}, C::{conds[c]}, A::{acts[a]}, {cv}, {av}, {es}, {ds})' for pos, icon, c, a, cv, av, es, ds in btns)
    print(f'    /* {i:3} */ &[{items}],')
print('];')
