    /// 0x42cf70 + costs (0x423790 and the build actions): `u`'s owner can afford `t`.
    fn affordable(&self, d: &Data, u: u32, t: u16) -> bool {
        let p = self.units[u as usize].player as usize;
        if !self.supply_ok(d, p, t) {
            return false;
        }
        let (m, g) = (d.dat.units.mineral_cost[t as usize] as i32, d.dat.units.gas_cost[t as usize] as i32);
        self.players.minerals[p] >= m && self.players.gas[p] >= g
    }

    /// 0x423540: some selected unit has energy for its cloak.
    fn cloak_energy(&self, d: &Data, s: &Selection) -> bool {
        if self.game_options & 0x800 != 0 {
            return true;
        }
        self.any_sel(s, |u| {
            let un = &self.units[u as usize];
            let t = match un.unit_type {
                1 | 0x10 | 100 | 99 | 0x68 | 0x33 => 10,
                8 | 0x15 => 9,
                _ => 0x2c,
            };
            let cost = (d.dat.techdata.energy_cost.get(t).copied().unwrap_or(0) as u8 as u32) << 8;
            un.energy as u32 >= cost
        })
    }

    /// 0x423930 / 0x423190: the larvae of the active hatchery (up to 12).
    fn nearby_larvae(&self, s: &Selection) -> Vec<u32> {
        let a = s.active;
        let (x, y) = self.unit_sprite_pos(a);
        let b = [x.wrapping_sub(0x80), y.wrapping_sub(0x80), x.wrapping_add(0x80), y.wrapping_add(0x80)];
        let mut search = self.search.clone();
        let start = search.units_in_finder_box(self, b);
        search
            .results(start)
            .into_iter()
            .filter(|&l| {
                let un = &self.units[l as usize];
                un.unit_type == 0x23 && un.connected_unit == a && self.sprites[un.sprite as usize].flags & super::sprite::sflag::HIDDEN == 0
            })
            .take(12)
            .collect()
    }
