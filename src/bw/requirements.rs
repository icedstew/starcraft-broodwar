/// 0x46d450 / 0x46e100 / 0x46d4c0 / 0x46d530 / 0x46d5a0: index of each id's list (the
/// word after the id), 0 for ids without one. Upgrades skip ids >= `limit`, which are
/// the per-level branch markers.
fn offsets(table: &[u16], count: usize, limit: u16) -> Vec<u16> {
    let mut out = vec![0u16; count];
    let mut i = 1;
    let mut id = table[1];
    while id != 0xffff {
        if id < limit && (id as usize) < count {
            out[id as usize] = i as u16 + 1;
        }
        while id != 0xffff {
            i += 1;
            id = table[i];
        }
        id = table[i + 1];
        i += 1;
    }
    out
}

fn order_offsets() -> &'static [u16] {
    static O: OnceLock<Vec<u16>> = OnceLock::new();
    O.get_or_init(|| offsets(ORDERS, 189, 0xffff))
}
fn unit_offsets() -> &'static [u16] {
    static O: OnceLock<Vec<u16>> = OnceLock::new();
    O.get_or_init(|| offsets(UNITS, 228, 0xffff))
}
/// 0x46e170: the type an addon is built from (its unit requirement list starts with
/// "current unit is"), 0xe4 for others.
pub fn addon_parent_type(t: u16) -> u16 {
    let off = unit_offsets().get(t as usize).copied().unwrap_or(0) as usize;
    if off != 0 && UNITS[off] == 0xff02 {
        UNITS[off + 1]
    } else {
        0xe4
    }
}

